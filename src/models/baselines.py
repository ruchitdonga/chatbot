"""Phase 4 intent baselines, logged to MLflow. Neither predicts slots.

- majority: each locale's most frequent training intent.
- bag_of_embeddings: mean of mBERT's static word-piece embeddings, then logistic regression,
  trained on the train split of all ten locales; C chosen on dev.

Writes predictions to artifacts/predictions/<baseline>/<partition>.jsonl and reports/baselines.md.
Run from the repo root: python -m src.models.baselines [--only majority]
"""
import argparse
import json
from collections import Counter

import mlflow
import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, f1_score
from sklearn.preprocessing import StandardScaler

from src.data.load import ROOT, configured_locales, load_config
from src.data.prepare import load_processed
from src.models.tracking import init_mlflow, lineage_params

C_GRID = [0.1, 1.0, 10.0]


def majority_predictions(train, examples):
    top = {}
    for loc in {ex["locale"] for ex in train}:
        top[loc] = Counter(ex["intent"] for ex in train if ex["locale"] == loc).most_common(1)[0][0]
    return [top[ex["locale"]] for ex in examples]


def mean_pool(token_ids, matrix):
    """Mean embedding row per utterance; zeros when an utterance has no tokens."""
    out = np.zeros((len(token_ids), matrix.shape[1]), dtype=np.float32)
    for i, ids in enumerate(token_ids):
        if ids:
            out[i] = matrix[ids].mean(axis=0)
    return out


def scores(examples, preds):
    """Per-locale intent accuracy and macro-F1, plus their unweighted mean over locales."""
    by_loc = {}
    for loc in dict.fromkeys(ex["locale"] for ex in examples):
        idx = [i for i, ex in enumerate(examples) if ex["locale"] == loc]
        gold, pred = [examples[i]["intent"] for i in idx], [preds[i] for i in idx]
        by_loc[loc] = {"accuracy": accuracy_score(gold, pred),
                       "macro_f1": f1_score(gold, pred, average="macro", zero_division=0)}
    mean = {k: float(np.mean([v[k] for v in by_loc.values()])) for k in ("accuracy", "macro_f1")}
    return by_loc, mean


def load_embeddings(model_name):
    from huggingface_hub import hf_hub_download
    from safetensors import safe_open

    with safe_open(hf_hub_download(model_name, "model.safetensors"), framework="np") as f:
        return f.get_tensor(next(k for k in f.keys() if k.endswith("word_embeddings.weight")))


def bag_of_embeddings(cfg, splits):
    from transformers import AutoTokenizer

    model = cfg["models"]["primary"]
    tokenizer = AutoTokenizer.from_pretrained(model)
    matrix = load_embeddings(model)
    feats = {part: mean_pool(tokenizer([ex["utt"] for ex in exs], add_special_tokens=False)["input_ids"], matrix)
             for part, exs in splits.items()}
    scaler = StandardScaler().fit(feats["train"])
    feats = {part: scaler.transform(x) for part, x in feats.items()}
    y = [ex["intent"] for ex in splits["train"]]

    best = None
    dev_acc = {}
    for c in C_GRID:
        clf = LogisticRegression(C=c, max_iter=1000, random_state=cfg["project"]["seed"]).fit(feats["train"], y)
        dev_acc[c] = scores(splits["dev"], clf.predict(feats["dev"]))[1]["accuracy"]
        if best is None or dev_acc[c] > dev_acc[best[0]]:
            best = (c, clf)
    c, clf = best
    params = {"encoder_embeddings": model, "classifier": "logistic_regression", "C": c,
              **{f"dev_accuracy_C_{k}": round(v, 4) for k, v in dev_acc.items()}}
    return params, {part: list(clf.predict(feats[part])) for part in ("dev", "test")}


def log_run(cfg, name, params, preds, splits):
    results = {}
    with mlflow.start_run(run_name=name):
        mlflow.log_params({**params, **lineage_params(cfg)})
        out_dir = ROOT / cfg["paths"]["artifacts"] / "predictions" / name
        out_dir.mkdir(parents=True, exist_ok=True)
        for part in ("dev", "test"):
            by_loc, mean = scores(splits[part], preds[part])
            results[part] = (by_loc, mean)
            mlflow.log_metrics({f"{part}_mean_{k}": v for k, v in mean.items()})
            mlflow.log_metrics({f"{part}_{loc}_{k}": v for loc, m in by_loc.items() for k, v in m.items()})
            path = out_dir / f"{part}.jsonl"
            with open(path, "w", encoding="utf-8") as f:
                for ex, p in zip(splits[part], preds[part]):
                    f.write(json.dumps({"id": ex["id"], "locale": ex["locale"], "gold": ex["intent"], "pred": p},
                                       ensure_ascii=False) + "\n")
            mlflow.log_artifact(str(path))
    return results


def write_report(cfg, all_results):
    names = list(all_results)
    lines = [
        "# Baseline Results",
        "",
        "Generated by `python -m src.models.baselines`. Intent only: neither baseline predicts slots, so slot F1 is "
        "not applicable. Means are unweighted over the ten locales. Test numbers are reported once; any choice "
        "(the C of logistic regression) was made on dev.",
        "",
        "| Locale | " + " | ".join(f"{n} test acc | {n} test macro-F1" for n in names) + " |",
        "|---|" + "---|---|" * len(names),
    ]
    for loc in configured_locales(cfg):
        lines.append(f"| {loc} | " + " | ".join(
            f"{all_results[n]['test'][0][loc]['accuracy']:.3f} | {all_results[n]['test'][0][loc]['macro_f1']:.3f}"
            for n in names) + " |")
    for part in ("test", "dev"):
        lines.append(f"| **{part} mean** | " + " | ".join(
            f"**{all_results[n][part][1]['accuracy']:.3f}** | **{all_results[n][part][1]['macro_f1']:.3f}**"
            for n in names) + " |")
    (ROOT / cfg["paths"]["reports"] / "baselines.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", choices=["majority", "bag_of_embeddings"])
    args = parser.parse_args()

    cfg = load_config()
    init_mlflow(cfg, "baselines")

    splits = {part: [ex for loc in configured_locales(cfg) for ex in load_processed(loc, part)]
              for part in ("train", "dev", "test")}
    all_results = {}
    if args.only in (None, "majority"):
        preds = {part: majority_predictions(splits["train"], splits[part]) for part in ("dev", "test")}
        all_results["majority"] = log_run(cfg, "majority", {"method": "per-locale majority intent"}, preds, splits)
    if args.only in (None, "bag_of_embeddings"):
        params, preds = bag_of_embeddings(cfg, splits)
        all_results["bag_of_embeddings"] = log_run(cfg, "bag_of_embeddings", params, preds, splits)

    write_report(cfg, all_results)
    for name, res in all_results.items():
        print(f"{name}: test mean accuracy {res['test'][1]['accuracy']:.4f}, macro-F1 {res['test'][1]['macro_f1']:.4f}")


if __name__ == "__main__":
    main()
