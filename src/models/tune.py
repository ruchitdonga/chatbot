"""Phase 5: Optuna study for the deployed model on the Run B setup.

Each trial trains on TRAIN_FRACTION of the Run B train split and is scored on the full dev split
(mean of dev intent accuracy and slot F1); MedianPruner stops trials that fall behind after each
epoch. Test data is never used. The study is stored in mlruns/optuna.db, so it resumes if stopped.
Writes reports/optuna_study.md with the best parameters and the command for the final run.
Run from the repo root: python -m src.models.tune --trials 10
"""
import argparse

import mlflow
import optuna

from src.data.load import ROOT, load_config
from src.models.tracking import init_mlflow
from src.models.train import train

TRAIN_FRACTION = 0.25
STUDY_NAME = "deployed-runB"


def objective(trial, cfg):
    overrides = {
        "learning_rate": trial.suggest_float("learning_rate", 1e-5, 6e-5, log=True),
        "epochs": trial.suggest_int("epochs", 2, 5),
        "slot_loss_weight": trial.suggest_float("slot_loss_weight", 0.5, 2.0),
    }
    return train(cfg, cfg["models"]["deployed"], "B", train_fraction=TRAIN_FRACTION, overrides=overrides,
                 run_name=f"optuna-trial-{trial.number}", trial=trial, save=False)


def write_report(cfg, study):
    best = study.best_trial
    p = best.params
    lines = [
        "# Optuna Study",
        "",
        f"Model `{cfg['models']['deployed']}`, Run B setup, {int(TRAIN_FRACTION * 100)}% of the train split per trial, "
        "scored on the full dev split (mean of dev intent accuracy and dev slot F1). Test data not used. "
        "Generated by `python -m src.models.tune`.",
        "",
        f"Best trial: #{best.number}, dev score {best.value:.4f}, learning rate {p['learning_rate']:.2e}, "
        f"epochs {p['epochs']}, slot loss weight {p['slot_loss_weight']:.2f}.",
        "",
        "Final Run B training with these parameters:",
        "",
        "```bash",
        f"python -m src.models.train --model {cfg['models']['deployed']} --run B "
        f"--learning-rate {p['learning_rate']:.2e} --epochs {p['epochs']} --slot-loss-weight {p['slot_loss_weight']:.2f}",
        "```",
        "",
        "| Trial | State | Learning rate | Epochs | Slot loss weight | Dev score |",
        "|---|---|---|---|---|---|",
    ]
    for t in study.trials:
        tp = t.params
        value = f"{t.value:.4f}" if t.value is not None else "-"
        lines.append(f"| {t.number} | {t.state.name} | {tp.get('learning_rate', 0):.2e} | {tp.get('epochs', '-')} "
                     f"| {tp.get('slot_loss_weight', 0):.2f} | {value} |")
    (ROOT / cfg["paths"]["reports"] / "optuna_study.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--trials", type=int, default=10)
    args = parser.parse_args()
    cfg = load_config()
    storage = f"sqlite:///{(ROOT / cfg['paths']['mlflow_tracking_uri'] / 'optuna.db').as_posix()}"
    study = optuna.create_study(
        study_name=STUDY_NAME, storage=storage, load_if_exists=True, direction="maximize",
        sampler=optuna.samplers.TPESampler(seed=cfg["project"]["seed"]),
        pruner=optuna.pruners.MedianPruner(n_startup_trials=3, n_warmup_steps=1))
    init_mlflow(cfg, "joint")
    with mlflow.start_run(run_name="optuna-study"):
        mlflow.log_params({"model": cfg["models"]["deployed"], "train_fraction": TRAIN_FRACTION, "trials": args.trials})
        study.optimize(lambda trial: objective(trial, cfg), n_trials=args.trials)
        mlflow.log_params({f"best_{k}": v for k, v in study.best_params.items()})
        mlflow.log_metric("best_dev_score", study.best_value)
    write_report(cfg, study)
    print(f"Best dev score {study.best_value:.4f} with {study.best_params}")


if __name__ == "__main__":
    main()
