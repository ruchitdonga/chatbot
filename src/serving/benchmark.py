"""Phase 8: latency benchmark (NFR-4: median NLU inference <= 300 ms on a 4-core CPU).

Times single utterances (batch size 1) with ONNX Runtime limited to serving.intra_op_threads threads,
after a warm-up: the NLU model alone, and the full /predict path (language ID, model, logging) through the API.
Writes reports/latency_report.md. Run from the repo root: python -m src.serving.benchmark [--fp32]
"""
import argparse
import os
import platform
import random
import statistics
import time
from pathlib import Path

from fastapi.testclient import TestClient

from src.data.load import ROOT, configured_locales, load_config
from src.data.prepare import load_processed
from src.serving.app import create_app
from src.serving.nlu import OnnxNLU

N, WARMUP = 300, 20


def timed(fn, texts):
    for text in texts[:WARMUP]:
        fn(text)
    times = []
    for text in texts:
        start = time.perf_counter()
        fn(text)
        times.append((time.perf_counter() - start) * 1000)
    return {"median": statistics.median(times), "p95": sorted(times)[int(0.95 * len(times))], "max": max(times)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--fp32", action="store_true", help="benchmark the fp32 model instead of INT8")
    args = parser.parse_args()
    cfg = load_config()
    rng = random.Random(cfg["project"]["seed"])
    texts = [ex["utt"] for loc in configured_locales(cfg) for ex in load_processed(loc, "test")]
    texts = rng.sample(texts, N)
    threads = cfg["serving"]["intra_op_threads"]
    run = Path(cfg["models"]["deployed_checkpoint"]).parent.name
    nlu = OnnxNLU(ROOT / cfg["serving"]["onnx_dir"] / run, threads=threads, quantized=not args.fp32)
    fb = cfg["fallback"]
    model_only = timed(lambda t: nlu.predict(t, fb["temperature"], fb["threshold"]), texts)
    cfg["serving"]["event_log"] = str(ROOT / "logs" / "benchmark_events.jsonl")
    client = TestClient(create_app(nlu=nlu, cfg=cfg))
    api = timed(lambda t: client.post("/predict", json={"text": t}), texts)

    variant = "fp32" if args.fp32 else "INT8"
    target = cfg["targets"]["median_nlu_latency_ms"]
    lines = [
        "# Latency Report", "",
        f"Generated by `python -m src.serving.benchmark{' --fp32' if args.fp32 else ''}`. {N} random test utterances, "
        f"batch size 1, {WARMUP} warm-up calls, ONNX Runtime with {threads} intra-op threads ({variant} model `{run}`).",
        f"Machine: {platform.processor() or platform.machine()}, {os.cpu_count()} logical CPUs; only {threads} threads "
        "are used, to approximate the spec's 4-core CPU.", "",
        "| Path | Median ms | p95 ms | Max ms |", "|---|---|---|---|",
        f"| NLU model only (tokenise + ONNX + decode) | {model_only['median']:.1f} | {model_only['p95']:.1f} | {model_only['max']:.1f} |",
        f"| Full /predict (language ID + model + logging, in-process) | {api['median']:.1f} | {api['p95']:.1f} | {api['max']:.1f} |",
        "", f"NFR-4 target: median NLU inference ≤ {target} ms: **{'met' if model_only['median'] <= target else 'missed'}**.",
        "End-to-end turn time including Rasa is measured in Phase 10.",
    ]
    (ROOT / cfg["paths"]["reports"] / "latency_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
