"""Build configs/swahili_words.txt: words that mark a message as Swahili for the language detector.

fastText lid.176 reads short Swahili as English or another language (34.5% of the MASSIVE sw-KE test split wrong,
102 of them "unsupported", which hands the chat to a person). A word qualifies when it appears in at least
MIN_SENTENCES Swahili training sentences and in no training sentence of the other nine locales, and is not one of
the Hinglish marker words (configs/faq.yaml `hinglish_words`), since Hinglish is not in MASSIVE.
Training data only; the result is checked on the test split (PROJECT_STATUS.md).

Run: python -m src.serving.swahili_words
"""
import re
from collections import Counter

import yaml

from src.data.load import ROOT, configured_locales, load_config
from src.data.prepare import load_processed

MIN_SENTENCES = 10
OUT = ROOT / "configs" / "swahili_words.txt"


def words(text):
    return set(re.findall(r"[a-z]+", text.casefold()))


def build(cfg):
    counts = {loc: Counter(w for r in load_processed(loc, "train") for w in words(r["utt"]))
              for loc in configured_locales(cfg)}
    elsewhere = set().union(*(c for loc, c in counts.items() if loc != "sw-KE"))
    # Only the Hinglish marker list: the FAQ topics also hold Swahili keywords ("oda yangu iko"), which must stay.
    hinglish = set(yaml.safe_load((ROOT / "configs" / "faq.yaml").read_text(encoding="utf-8"))["hinglish_words"])
    return sorted(w for w, n in counts["sw-KE"].items()
                  if n >= MIN_SENTENCES and len(w) >= 3 and w not in elsewhere and w not in hinglish)


def main():
    found = build(load_config())
    OUT.write_text("# Generated by src/serving/swahili_words.py from MASSIVE training data; do not edit by hand.\n"
                   + "\n".join(found) + "\n", encoding="utf-8")
    print(f"{len(found)} words -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
