"""Phase 3: check slot-label alignment against the real mBERT and XLM-R tokenizers.

For every processed example and both tokenizers: labels must match the token count and be in
range. Counts slots no token starts inside (lost) and slots whose boundary falls inside a
token (ragged), plus token lengths for choosing max_length.
Writes reports/alignment_report.md. Run from the repo root: python -m src.data.check_alignment
"""
import json

from transformers import AutoTokenizer

from src.data.eda import percentile
from src.data.load import ROOT, configured_locales, load_config
from src.data.prepare import SPLITS_DIR, bio_labels, load_processed, lost_spans, ragged_spans


def check(tokenizer, examples, tag2id):
    enc = tokenizer([ex["utt"] for ex in examples], return_offsets_mapping=True)
    spans = lost = ragged = unknown = tokens = 0
    lengths = []
    for ex, ids, offsets in zip(examples, enc["input_ids"], enc["offset_mapping"]):
        unknown += sum(i == tokenizer.unk_token_id for i in ids)
        tokens += sum(s != e for s, e in offsets)
        labels = bio_labels(offsets, ex["spans"], tag2id)
        if len(labels) != len(ids) or not all(lab == -100 or 0 <= lab < len(tag2id) for lab in labels):
            raise ValueError(f"misaligned labels for {ex['locale']} id {ex['id']}")
        spans += len(ex["spans"])
        lost += lost_spans(offsets, ex["spans"])
        ragged += ragged_spans(offsets, ex["spans"])
        lengths.append(len(ids))
    return {"examples": len(examples), "spans": spans, "lost": lost, "ragged": ragged,
            "unknown_pct": 100 * unknown / tokens,
            "p99_tokens": percentile(lengths, 0.99), "max_tokens": max(lengths)}


def main():
    cfg = load_config()
    labels = json.loads((SPLITS_DIR / "labels.json").read_text(encoding="utf-8"))
    tag2id = {t: i for i, t in enumerate(labels["slot_tags"])}
    models = [cfg["models"]["primary"], cfg["models"]["comparison"]]
    rows = []
    for model in models:
        tokenizer = AutoTokenizer.from_pretrained(model)
        for loc in configured_locales(cfg):
            examples = [ex for part in cfg["dataset"]["partitions"] for ex in load_processed(loc, part)]
            rows.append((model, loc, check(tokenizer, examples, tag2id)))

    lines = [
        "# Slot-Label Alignment Report",
        "",
        "Generated by `python -m src.data.check_alignment` over all partitions. Every example's labels matched its "
        "token count and were in range (the script stops on the first failure).",
        "",
        "- **Lost**: slots no token starts inside, so they get no B- tag and cannot be predicted.",
        "- **Ragged**: slots whose start or end falls inside a token, so even perfect tags give a span "
        "a few characters too long or short.",
        "- **Unknown**: share of tokens the tokenizer maps to its unknown token, i.e. text the model cannot see.",
        "",
        "| Tokenizer | Locale | Examples | Slots | Unknown tokens | Lost | Ragged | p99 tokens | Max tokens |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for model, loc, r in rows:
        lines.append(f"| {model} | {loc} | {r['examples']:,} | {r['spans']:,} | {r['unknown_pct']:.1f}% "
                     f"| {r['lost']} ({100 * r['lost'] / r['spans']:.2f}%) "
                     f"| {r['ragged']} ({100 * r['ragged'] / r['spans']:.2f}%) | {r['p99_tokens']} | {r['max_tokens']} |")
    out = ROOT / cfg["paths"]["reports"] / "alignment_report.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Alignment report written to {out}")
    for model in models:
        print(model, "max tokens:", max(r["max_tokens"] for m, _, r in rows if m == model))


if __name__ == "__main__":
    main()
