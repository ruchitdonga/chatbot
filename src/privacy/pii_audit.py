"""Phase 2 PII audit: count PII-like content per locale without printing any utterance.

Writes reports/pii_audit.md. Run from the repo root: python -m src.privacy.pii_audit
"""
import re

from src.data.load import ROOT, configured_locales, load_config, load_locale, parse_slots

EMAIL_RE = re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+")
# Six or more digits, optionally separated by spaces or hyphens: phone- or order-number-like.
LONG_NUMBER_RE = re.compile(r"\d(?:[\s-]?\d){5,}")


def audit(records, pii_slots):
    slot_hits = {slot: 0 for group in pii_slots.values() for slot in group}
    any_slot = emails = numbers = 0
    for r in records:
        labels = {label for label, _ in parse_slots(r["annot_utt"]) or []}
        found = labels & slot_hits.keys()
        for slot in found:
            slot_hits[slot] += 1
        any_slot += bool(found)
        emails += bool(EMAIL_RE.search(r["utt"]))
        numbers += bool(LONG_NUMBER_RE.search(r["utt"]))
    return {"records": len(records), "any_pii_slot": any_slot, "slots": slot_hits,
            "email_pattern": emails, "long_number_pattern": numbers}


def main():
    cfg = load_config()
    pii_slots = cfg["privacy"]["pii_slot_types"]
    results = {loc: audit(load_locale(cfg, loc), pii_slots) for loc in configured_locales(cfg)}
    slots = [slot for group in pii_slots.values() for slot in group]
    lines = [
        "# PII Audit",
        "",
        "Generated by `python -m src.privacy.pii_audit`. Counts are utterances, not mentions. "
        "No utterance text is reproduced here.",
        "",
        "Slot groups (from `privacy.pii_slot_types` in the config): "
        + "; ".join(f"{g.replace('_', ' ')}: {', '.join(f'`{s}`' for s in ss)}" for g, ss in pii_slots.items()) + ".",
        "Pattern columns count utterances whose raw text matches an email pattern or a run of 6+ digits.",
        "",
        "| Locale | Utterances | Any PII slot | " + " | ".join(f"`{s}`" for s in slots)
        + " | Email pattern | 6+ digit number |",
        "|---|---|---|" + "---|" * len(slots) + "---|---|",
    ]
    for loc, a in results.items():
        lines.append(
            f"| {loc} | {a['records']:,} | {a['any_pii_slot']:,} ({100 * a['any_pii_slot'] / a['records']:.1f}%) | "
            + " | ".join(f"{a['slots'][s]:,}" for s in slots)
            + f" | {a['email_pattern']} | {a['long_number_pattern']} |"
        )
    out = ROOT / cfg["paths"]["reports"] / "pii_audit.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"PII audit written to {out}")


if __name__ == "__main__":
    main()
